"""The parity report of a parallel run (`migration/parity.json`) and its rendering (`docs/assessment/parity.md`)."""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

from lakemig.parity.compare import ProfileMismatch, SliceResult
from lakemig.parity.spec import Spec

FORMAT_VERSION = 1


@dataclass(frozen=True)
class TableResult:
    relation: str
    key: tuple[str, ...]
    slice_column: str | None
    compared_columns: tuple[str, ...]
    slices: tuple[SliceResult, ...]

    @property
    def equal(self) -> bool:
        return all(s.equal for s in self.slices)

    @property
    def rows(self) -> tuple[int, int]:
        return sum(s.source_rows for s in self.slices), sum(s.target_rows for s in self.slices)


@dataclass(frozen=True)
class Report:
    format_version: int
    measured_at: str
    spec_digest: str
    source_repository: str
    source_commit: str
    lakehouse_ref: str
    target_catalog: str
    engine_version: str
    business_dates: tuple[str, str]
    # Business date (or "every date") -> run id of the publication the comparison read.
    publications: Mapping[str, str]
    tables: tuple[TableResult, ...]

    @property
    def accepted(self) -> bool:
        return all(t.equal for t in self.tables)

    def write(self, path: Path) -> None:
        path.write_text(json.dumps(asdict(self), indent=2) + "\n", encoding="utf-8")

    @classmethod
    def read(cls, path: Path) -> Report:
        raw = json.loads(path.read_text(encoding="utf-8"))
        tables = tuple(
            TableResult(
                relation=t["relation"],
                key=tuple(t["key"]),
                slice_column=t["slice_column"],
                compared_columns=tuple(t["compared_columns"]),
                slices=tuple(_slice(s) for s in t["slices"]),
            )
            for t in raw.pop("tables")
        )
        dates = raw.pop("business_dates")
        return cls(**raw, business_dates=(dates[0], dates[1]), tables=tables)

    def problems(self, spec: Spec) -> list[str]:
        """The report must cover the spec it claims to have run."""
        problems = []
        if self.spec_digest != spec.digest:
            problems.append(
                f"the report ran spec {self.spec_digest}, migration/parity.yaml is {spec.digest}: make parity"
            )
        compared = [t.relation for t in self.tables]
        expected = [t.relation for t in spec.tables]
        if compared != expected:
            problems.append(f"the report compares {compared}, the spec lists {expected}: make parity")
        return problems


def _slice(raw: dict[str, Any]) -> SliceResult:
    mismatches = tuple(ProfileMismatch(**m) for m in raw.pop("profile_mismatches"))
    return SliceResult(**{**raw, "examples": tuple(raw["examples"]), "profile_mismatches": mismatches})


def parity_md(report: Report, spec: Spec, exempted: Mapping[str, str] | None = None) -> str:
    verdict = "accepted" if report.accepted else "**not accepted**"
    lines = [
        "# Parity of the parallel run",
        "",
        "Generated by `make parity` from `migration/parity.json` (ADR 0008); do not edit.",
        "",
        f"Business dates {report.business_dates[0]} to {report.business_dates[1]}: the migration is {verdict}.",
        "",
        f"- Source: [{_short(report.source_commit)}]({report.source_repository}/tree/{report.source_commit}), "
        f"lakehouse at `{report.lakehouse_ref}`",
        f"- Target: catalog `{report.target_catalog}`, {report.engine_version}, "
        f"{len(report.publications)} publications read",
        f"- Spec: `migration/parity.yaml` ({report.spec_digest})",
        "",
        "| Table | Slices | Source rows | Target rows | Compared columns | Differing buckets | Rows that differ "
        "| Within tolerance | Result |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---|",
    ]
    for table in report.tables:
        source_rows, target_rows = table.rows
        differ = sum(s.missing_in_target + s.unexpected_in_target + sum(s.different.values()) for s in table.slices)
        within = sum(sum(s.within_tolerance.values()) for s in table.slices)
        result = "equal" if table.equal else "**differs**"
        if table.relation in spec.zero_difference:
            result += " (zero difference required)"
        lines.append(
            f"| `{table.relation}` | {len(table.slices)} | {source_rows:,} | {target_rows:,} | "
            f"{len(table.compared_columns)} | {sum(s.buckets_differing for s in table.slices)} | {differ:,} | "
            f"{within:,} | {result} |"
        )
    lines += ["", "## How each table is compared", ""]
    for table in report.tables:
        table_spec = spec.table(table.relation)
        slicing = f"each `{table.slice_column}` on its own" if table.slice_column else "the whole table"
        lines.append(f"- `{table.relation}`: key `{', '.join(table.key)}`, {slicing}.")
        if table_spec.pseudonymize:
            pairs = ", ".join(f"`{c}` ({n})" for c, n in table_spec.pseudonymize.items())
            lines.append(f"  Pseudonymized on the source side before the comparison: {pairs}.")
        if table_spec.tolerance:
            pairs = ", ".join(f"`{c}` ± {t:g}" for c, t in table_spec.tolerance.items())
            lines.append(f"  Tolerances: {pairs}.")
        for column, reason in table_spec.on_premises.items():
            lines.append(f"  `{column}` stays on premises: {reason}")
    lineage = ", ".join(f"`{c}`" for c in sorted(spec.lineage))
    lines += ["", f"Never compared, written by each platform about its own run: {lineage}."]
    if exempted:
        lines += ["", "## Published tables not compared", ""]
        lines += [f"- `{relation}`: {' '.join(reason.split())}" for relation, reason in sorted(exempted.items())]
    lines += _differences(report.tables)
    return "\n".join(lines) + "\n"


def _differences(tables: Sequence[TableResult]) -> list[str]:
    lines: list[str] = []
    for table in tables:
        for result in table.slices:
            if result.equal and not result.within_tolerance:
                continue
            if not lines:
                lines += ["", "## Differences", ""]
            where = f"`{table.relation}`" + (f" on {result.slice}" if result.slice else "")
            lines.append(f"### {where}")
            lines.append("")
            lines.append(
                f"{result.source_rows:,} source rows, {result.target_rows:,} target rows; "
                f"{result.buckets_differing} of {result.buckets} buckets differ, {result.buckets_inspected} inspected; "
                f"{result.missing_in_target} missing in the target, {result.unexpected_in_target} unexpected; "
                f"{result.duplicate_keys} duplicate keys."
            )
            for column, count in result.different.items():
                lines.append(f"- `{column}` differs in {count:,} rows")
            for column, count in result.within_tolerance.items():
                lines.append(f"- `{column}` differs within its tolerance in {count:,} rows")
            for mismatch in result.profile_mismatches:
                lines.append(
                    f"- profile of `{mismatch.column}`, {mismatch.metric}: "
                    f"source {mismatch.source}, target {mismatch.target}"
                )
            for example in result.examples:
                lines.append(f"- {example}")
            lines.append("")
    return lines


def _short(commit: str) -> str:
    return commit[:12]
