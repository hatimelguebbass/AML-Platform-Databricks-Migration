"""Renders the assessment documents under `docs/assessment/` from the committed migration files."""

from __future__ import annotations

from collections import Counter
from collections.abc import Iterable, Sequence

from lakemig.assessment.classification import Classification, Level
from lakemig.assessment.waves import Fate, Plan
from lakemig.cost.estimate import SCENARIOS, Assumptions, Estimate
from lakemig.export.policy import ExportPlan, Selection, SelectionKind
from lakemig.inventory.model import DataObject, Inventory, ObjectKind

HEADER = "<!-- Generated by `make assessment` from the files in migration/. Edit those, not this file. -->\n"
MB = 1_000_000


def inventory_md(inventory: Inventory) -> str:
    objects = inventory.objects
    out = [
        HEADER,
        "# Source inventory\n",
        f"Collected from [{_repo_name(inventory)}]({inventory.source_repository}) at commit "
        f"`{inventory.source_commit[:12]}`, "
        f"through Trino {inventory.engine_version}.\n",
        "## Summary\n",
        _table(
            ["Kind", "Objects", "Rows", "Data (MB)", "Tests"],
            [
                [kind.value, str(len(group)), _int(_rows(group)), _mb(_bytes(group)), str(sum(o.tests for o in group))]
                for kind, group in _by_kind(objects)
            ],
        ),
        "## Objects\n",
        _table(
            ["Relation", "Kind", "Materialization", "Columns", "Rows", "Data (MB)", "Files", "Tests"],
            [
                [
                    f"`{o.relation}`",
                    o.kind.value,
                    o.materialization or "",
                    str(len(o.columns)),
                    _int(o.volume.rows) if o.volume else "",
                    _mb(o.volume.data_bytes) if o.volume else "",
                    _int(o.volume.data_files) if o.volume and o.volume.data_files is not None else "",
                    str(o.tests) if o.tests else "",
                ]
                for o in objects
            ],
        ),
        "## SQL functions\n",
        "Calls in the compiled models, and how the translator renders each function in Databricks SQL.\n",
        _table(["Function", "Calls", "Models", "Databricks SQL", "Conversion"], _function_rows(inventory)),
        "## Project macros\n",
        _table(
            ["Macro", "Used by"],
            [[f"`{m}`", str(n)] for m, n in sorted(Counter(m for o in objects for m in o.macros).items())],
        ),
        "## Access rules\n",
        "Trino file-based access control, in evaluation order (first match wins).\n",
        _table(
            ["Scope", "Users", "Catalog", "Schema", "Allow"],
            [[r.scope, f"`{r.users}`", r.catalog or "*", r.schema or "*", r.allow] for r in inventory.access_rules],
        ),
    ]
    return "\n".join(out)


def classification_md(inventory: Inventory, classification: Classification) -> str:
    levels = Counter(c.level for c in classification.columns)
    out = [
        HEADER,
        "# Column classification\n",
        "Levels: `direct` identifies a person on its own; `indirect` only combined with other data; "
        "`none` does not relate to a person. "
        "Policy: [`migration/classification.yaml`](../../migration/classification.yaml).\n",
        _table(["Level", "Columns"], [[level.value, str(levels[level])] for level in Level]),
        "## Columns relating to a person\n",
        _table(
            ["Relation", "Direct", "Indirect"],
            [
                [
                    f"`{o.relation}`",
                    _names(classification.of(o.relation), Level.DIRECT),
                    _names(classification.of(o.relation), Level.INDIRECT),
                ]
                for o in inventory.objects
                if any(level is not Level.NONE for level in classification.of(o.relation).values())
            ],
        ),
    ]
    return "\n".join(out)


def waves_md(plan: Plan, inventory: Inventory, classification: Classification) -> str:
    objects = inventory.by_relation()
    out = [
        HEADER,
        "# Migration waves\n",
        "Plan: [`migration/waves.yaml`](../../migration/waves.yaml). An exported object is computed on premises "
        "and shipped without its direct identifiers; a rebuilt one is recomputed in the cloud from earlier waves.\n",
        "## Summary\n",
        _table(
            ["Wave", "Objects", "Exported", "Rebuilt", "Rows", "Data (MB)"],
            [
                [
                    f"{w.number}. {w.name}",
                    str(len(w.objects)),
                    str(sum(f is Fate.EXPORT for f in w.objects.values())),
                    str(sum(f is Fate.REBUILD for f in w.objects.values())),
                    _int(_rows(objects[r] for r in w.objects)),
                    _mb(_bytes(objects[r] for r in w.objects)),
                ]
                for w in plan.waves
            ]
            + [
                [
                    "Kept on premises",
                    str(len(plan.on_premises)),
                    "",
                    "",
                    _int(_rows(objects[r] for r in plan.on_premises)),
                    _mb(_bytes(objects[r] for r in plan.on_premises)),
                ],
                ["Retired", str(len(plan.retired)), "", "", "", ""],
            ],
        ),
    ]
    for wave in plan.waves:
        out += [
            f"## Wave {wave.number}: {wave.name}\n",
            f"{wave.goal}\n",
            _table(
                [
                    "Relation",
                    "Fate",
                    "Rows",
                    "Data (MB)",
                    "Direct identifiers left on premises",
                    "Indirect identifiers",
                ],
                [
                    [
                        f"`{relation}`",
                        fate.value,
                        *_volume_cells(objects[relation]),
                        _names(classification.of(relation), Level.DIRECT) if fate is Fate.EXPORT else "",
                        _names(classification.of(relation), Level.INDIRECT),
                    ]
                    for relation, fate in wave.objects.items()
                ],
            ),
        ]
    out += [
        "## Kept on premises\n",
        _table(["Relation", "Reason"], [[f"`{r}`", reason] for r, reason in plan.on_premises.items()]),
        "## Retired\n",
        _table(["Relation", "Replaced by"], [[f"`{r}`", by] for r, by in plan.retired.items()]),
    ]
    return "\n".join(out)


def boundary_md(plan: ExportPlan, detectors: Sequence[tuple[str, str]]) -> str:
    out = [
        HEADER,
        "# What crosses the boundary\n",
        "Policy: [`migration/export.yaml`](../../migration/export.yaml), decided in "
        "[ADR 0003](../adr/0003-hybrid-boundary.md). Every column of every exported object, and what "
        "reaches the landing zone. Direct identifiers never cross; indirect ones cross only with the "
        "treatment named here.\n",
        "## Selections\n",
        _table(
            ["Relation", "Delivered as", "Rows of a delivery", "Row order"],
            [
                [f"`{t.relation}`", f"`{t.name}`", _selection(t.selection), ", ".join(f"`{c}`" for c in t.order_by)]
                for t in plan.tables
            ],
        ),
    ]
    for t in plan.tables:
        out += [
            f"## `{t.relation}`\n",
            _table(
                ["Column", "Level", "Treatment", "Delivered column"],
                [
                    [
                        f"`{c.source}`",
                        c.level.value,
                        c.treatment.value + (f" ({c.namespace})" if c.namespace else ""),
                        f"`{c.output}`" if c.output else "",
                    ]
                    for c in t.columns
                ],
            ),
        ]
    groups = ", ".join(" + ".join(f"`{c}`" for c in g) for g in plan.known_names.names)
    out += [
        "## PII gate\n",
        "Scans every string value of a delivery after the treatments; one match blocks the delivery.\n",
        _table(["Detector", "Looks for"], [[f"`{n}`", d] for n, d in detectors]),
        f"`person_name` uses the names {groups} of `{plan.known_names.relation}`, read at the export's "
        "source commit, on premises.\n",
        "### Exemptions\n",
        _table(
            ["Column", "Detector", "Reason"],
            [[f"`{e.relation}.{e.column}`", f"`{e.detector}`", e.reason] for e in plan.exemptions],
        )
        if plan.exemptions
        else "None.\n",
    ]
    return "\n".join(out)


def _selection(selection: Selection) -> str:
    if selection.kind is SelectionKind.SNAPSHOT:
        return "the whole table"
    if selection.kind is SelectionKind.BUSINESS_DATE:
        return f"`{selection.argument}` = business date"
    return f"change events of the capture runs of the business date into `{selection.argument}`"


def cost_md(estimates: Sequence[Estimate], assumptions: Assumptions, migrated_bytes: int, prices_retrieved: str) -> str:
    planned = estimates[0]
    out = [
        HEADER,
        "# Cost estimate of the Azure window\n",
        "Azure retail list prices (`migration/azure-prices.json`), "
        f"for a window of {planned.window_days} days, before discounts and credits. "
        f"Data migrated: {_mb(migrated_bytes)} MB (exported and rebuilt objects of the inventory). "
        "Assumptions and their basis: [`migration/cost-assumptions.yaml`](../../migration/cost-assumptions.yaml).\n",
        "## By region\n",
        _table(
            ["Region", *[f"{s.capitalize()} ({planned.currency})" for s in SCENARIOS]],
            [[e.region, *[f"{e.total(s):.2f}" for s in SCENARIOS]] for e in estimates],
        ),
        f"## Lines, {planned.region}\n",
        _table(
            [
                "Item",
                "Meter",
                "Unit price",
                "Unit",
                *[f"Quantity {s}" for s in SCENARIOS],
                *[f"Cost {s}" for s in SCENARIOS],
            ],
            [
                [
                    line.name,
                    line.meter,
                    f"{line.unit_price:g}",
                    line.unit,
                    *[f"{line.quantity.get(s):.2f}" for s in SCENARIOS],
                    *[f"{line.cost.get(s):.2f}" for s in SCENARIOS],
                ]
                for line in planned.lines
            ],
        ),
        "## Basis\n",
        *[f"- **{u.name}**: {u.basis}" for u in assumptions.usage],
        f"- **Lakehouse storage**: {assumptions.storage_basis}\n",
    ]
    return "\n".join(out)


def migrated_bytes(plan: Plan, inventory: Inventory) -> int:
    objects = inventory.by_relation()
    return _bytes(objects[r] for w in plan.waves for r in w.objects)


def _function_rows(inventory: Inventory) -> list[list[str]]:
    calls: Counter[str] = Counter()
    models: Counter[str] = Counter()
    for obj in inventory.objects:
        calls.update(obj.functions)
        models.update(obj.functions.keys())
    rows = []
    for name, targets in inventory.function_translations.items():
        rendered = ", ".join(f"`{t}`" if t else "unknown" for t in targets)
        rows.append([f"`{name}`", str(calls[name]), str(models[name]), rendered, _conversion(name, targets)])
    return sorted(rows, key=lambda r: (_ORDER[r[4]], r[0]))


_ORDER = {"manual": 0, "check semantics": 1, "same name": 2}


def _conversion(name: str, targets: tuple[str | None, ...]) -> str:
    if None in targets:
        return "manual"
    if targets == (name,):
        return "same name"
    return "check semantics"


def _names(levels: dict[str, Level], level: Level) -> str:
    return ", ".join(f"`{c}`" for c, lv in levels.items() if lv is level)


def _volume_cells(obj: DataObject) -> tuple[str, str]:
    return (_int(obj.volume.rows), _mb(obj.volume.data_bytes)) if obj.volume else ("", "")


def _rows(objects: Iterable[DataObject]) -> int:
    return sum(o.volume.rows for o in objects if o.volume)


def _bytes(objects: Iterable[DataObject]) -> int:
    return sum(o.volume.data_bytes or 0 for o in objects if o.volume)


def _by_kind(objects: Iterable[DataObject]) -> list[tuple[ObjectKind, list[DataObject]]]:
    groups: dict[ObjectKind, list[DataObject]] = {}
    for obj in objects:
        groups.setdefault(obj.kind, []).append(obj)
    return sorted(groups.items())


def _int(value: int) -> str:
    return f"{value:,}"


def _mb(value: int | None) -> str:
    return "" if value is None else f"{value / MB:,.1f}"


def _repo_name(inventory: Inventory) -> str:
    return inventory.source_repository.rstrip("/").rsplit("/", 1)[-1]


def _table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines) + "\n"
