"""Unity Catalog policy of the dbt models, checked against the classification and the export policy.

Every column of a model carries the level of its name as a `classification` tag, so the sensitivity
the assessment decided is what Unity Catalog shows and searches. Every column named like a column
the export pseudonymizes holds keyed pseudonyms and carries the pseudonym mask. A model that adds a
column, or loses a tag or a mask, fails CI until its YAML declares what the policy requires.
"""

from __future__ import annotations

from collections.abc import Collection, Iterator, Mapping
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from lakemig.assessment.classification import Classification, Level, Policy, classify
from lakemig.inventory.model import Column, DataObject, ObjectKind

TAG = "classification"
# Relative to the catalog of the dbt session, so one name serves every environment.
PSEUDONYM_MASK = "governance.mask_pseudonym"
HEADER = "<!-- Generated by `make assessment` from transform/models/. Edit the models' YAML, not this file. -->\n"


@dataclass(frozen=True)
class ModelColumn:
    name: str
    data_type: str
    tags: Mapping[str, str] = field(default_factory=dict)
    mask: str | None = None


@dataclass(frozen=True)
class Model:
    schema: str
    name: str
    columns: tuple[ModelColumn, ...]
    path: Path
    # Why the parallel run does not compare this model with the source (`meta.parity_exemption`).
    parity_exemption: str | None = None

    @property
    def relation(self) -> str:
        return f"{self.schema}.{self.name}"


def read_models(project: Path) -> tuple[Model, ...]:
    """Models declared with columns under `models/`; the first directory below it is the schema."""
    models: list[Model] = []
    root = project / "models"
    for path in sorted(root.rglob("*.yml")):
        raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        schema = path.relative_to(root).parts[0]
        for entry in raw.get("models", ()):
            columns = tuple(_column(c) for c in entry.get("columns", ()))
            meta = (entry.get("config") or {}).get("meta") or {}
            if columns:
                models.append(Model(schema, entry["name"], columns, path, meta.get("parity_exemption")))
    return tuple(models)


def _column(raw: Mapping[str, Any]) -> ModelColumn:
    mask = raw.get("column_mask")
    return ModelColumn(
        name=raw["name"],
        data_type=raw.get("data_type", ""),
        tags={str(k): str(v) for k, v in (raw.get("databricks_tags") or {}).items()},
        mask=mask["function"] if mask else None,
    )


def classify_models(models: Collection[Model], policy: Policy) -> Classification:
    objects = [
        DataObject(m.schema, m.name, ObjectKind.MODEL, tuple(Column(c.name, c.data_type) for c in m.columns))
        for m in models
    ]
    return classify(objects, policy)


def check(models: Collection[Model], classification: Classification, pseudonymized: Collection[str]) -> list[str]:
    problems = classification.problems()
    for model, column, level in _levels(models, classification):
        where = f"{model.path}: {model.relation}.{column.name}"
        if level is None:
            continue
        expected = {TAG: level.value} if level is not Level.NONE else {}
        if level is Level.DIRECT:
            problems.append(f"{where}: direct identifier in a cloud model")
        elif dict(column.tags) != expected:
            problems.append(f"{where}: databricks_tags {dict(column.tags) or '{}'}, the policy requires {expected}")
        must_mask = column.name in pseudonymized
        if must_mask and column.mask != PSEUDONYM_MASK:
            problems.append(f"{where}: holds pseudonyms, needs column_mask {{function: {PSEUDONYM_MASK}}}")
        elif not must_mask and column.mask is not None:
            problems.append(f"{where}: column_mask {column.mask} on a column that holds no pseudonym")
    return problems


def _levels(
    models: Collection[Model], classification: Classification
) -> Iterator[tuple[Model, ModelColumn, Level | None]]:
    for model in models:
        levels = classification.of(model.relation)
        for column in model.columns:
            yield model, column, levels.get(column.name)


def policy_md(models: Collection[Model], classification: Classification) -> str:
    rows = []
    for model, column, level in _levels(models, classification):
        if level is Level.NONE and column.mask is None:
            continue
        rows.append(
            f"| `{model.relation}` | `{column.name}` | {level.value if level else '?'} | "
            f"{'`' + column.mask + '`' if column.mask else ''} |"
        )
    tagged = sum(1 for _, _, level in _levels(models, classification) if level is Level.INDIRECT)
    masked = sum(1 for m in models for c in m.columns if c.mask)
    return "\n".join(
        [
            HEADER,
            "# Unity Catalog policy of the transformations\n",
            "Rendered from the dbt models (`transform/models/**/*.yml`), checked against the classification "
            "and the export policy. Each column below carries the tag "
            f"`{TAG}` with its level; masked columns read as null outside the groups "
            "`aml-compliance`, `aml-pipeline` and, during the migration, `aml-migration` (ADR 0005, 0008).\n",
            "| Models | Columns | Tagged indirect | Masked |",
            "|---|---|---|---|",
            f"| {len(models)} | {sum(len(m.columns) for m in models)} | {tagged} | {masked} |\n",
            "| Relation | Column | Level | Mask |",
            "|---|---|---|---|",
            *rows,
            "",
        ]
    )
